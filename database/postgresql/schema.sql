-- AERIS PostgreSQL schema. Safe to apply to a newly created or already initialized database.
CREATE TABLE IF NOT EXISTS monitored_area (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255), latitude DOUBLE PRECISION NOT NULL, longitude DOUBLE PRECISION NOT NULL,
    active BOOLEAN NOT NULL, archived BOOLEAN NOT NULL DEFAULT FALSE, last_error VARCHAR(255),
    CONSTRAINT valid_coordinates CHECK (latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180)
);
CREATE TABLE IF NOT EXISTS smog_reading (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id BIGINT REFERENCES monitored_area(id), aqi DOUBLE PRECISION, pm25 DOUBLE PRECISION, pm10 DOUBLE PRECISION,
    source VARCHAR(255), timestamp TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT unique_area_reading UNIQUE(area_id,timestamp,source)
);
CREATE TABLE IF NOT EXISTS alert_preference (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id BIGINT REFERENCES monitored_area(id), aqi_threshold INTEGER NOT NULL,
    enabled BOOLEAN NOT NULL, system_rule BOOLEAN NOT NULL DEFAULT FALSE,
    above_threshold BOOLEAN NOT NULL, last_evaluated_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT valid_aqi_threshold CHECK (aqi_threshold BETWEEN 1 AND 500)
);
CREATE TABLE IF NOT EXISTS smog_alert (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id BIGINT REFERENCES monitored_area(id), preference_id BIGINT, reading_id BIGINT REFERENCES smog_reading(id),
    message VARCHAR(255), status VARCHAR(255), created_at TIMESTAMP(6) WITH TIME ZONE
);
-- preference_id intentionally remains a historical reference after a preference is removed.
ALTER TABLE monitored_area ADD COLUMN IF NOT EXISTS custom_location BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE smog_reading ADD COLUMN IF NOT EXISTS provider_location VARCHAR(500);
ALTER TABLE alert_preference ADD COLUMN IF NOT EXISTS last_evaluated_source VARCHAR(255);
CREATE INDEX IF NOT EXISTS readings_by_location_time ON smog_reading(area_id,source,timestamp DESC);
CREATE INDEX IF NOT EXISTS enabled_preferences_by_location ON alert_preference(area_id,enabled);
CREATE INDEX IF NOT EXISTS alerts_by_preference_time ON smog_alert(preference_id,created_at DESC);
CREATE INDEX IF NOT EXISTS alerts_by_time ON smog_alert(created_at DESC);
